import { AlertTriangle, Zap } from 'lucide-react';

export function DemoNotice() {
  return (
    <div className="alert alert-warning" role="alert">
      <AlertTriangle className="alert-icon" size={18} />
      <div>
        <strong>Demo Mode Active</strong> — Sample responses are shown below. To use live AI,
        add your <code>GEMINI_API_KEY</code> to <code>server/.env</code> and restart the server.
      </div>
    </div>
  );
}

export function LiveNotice() {
  return (
    <div className="alert alert-success" role="alert">
      <Zap className="alert-icon" size={18} />
      <div>
        <strong>Live Mode Active</strong> — Responses are generated by Google Gemini AI in real time.
      </div>
    </div>
  );
}

export function ErrorAlert({ message }) {
  if (!message) return null;
  return (
    <div className="alert alert-error" role="alert">
      <AlertTriangle className="alert-icon" size={18} />
      <div>{message}</div>
    </div>
  );
}

export function LoadingState({ message = 'Generating with AI...' }) {
  return (
    <div className="loading-state">
      <div className="spinner dark" style={{ width: 40, height: 40, borderWidth: 3 }} />
      <p>{message}</p>
    </div>
  );
}
